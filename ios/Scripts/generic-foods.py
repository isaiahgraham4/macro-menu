def rows(folder, name):
    with open(folder / name, newline="", encoding="utf-8") as handle:
        yield from csv.DictReader(handle)


def diet(name):
    """The food's DIET entry as `DietInfo` JSON; a None (not sure) is left out, so the app reads it as unknown."""
    meat, allergens, may, vg = DIET[name]
    info = {"meat": None if meat is None else sorted(meat), "al": None if allergens is None else sorted(allergens),
            "may": sorted(may) or None, "vg": vg, "src": "curated"}
    return {key: value for key, value in info.items() if value is not None}


def check_diet(names):
    problems = [f"{name}: no DIET entry" for name in names if name not in DIET]
    problems += [f"{name}: DIET entry for a food that isn't in FOODS" for name in DIET if name not in names]
    for name, (meat, allergens, may, vg) in DIET.items():
        if (vg is not None) != (meat == []):
            problems.append(f"{name}: vegan or vegetarian only when it has no meat")
        if vg == "vegan" and {"milk", "egg"} & set((allergens or []) + may):
            problems.append(f"{name}: vegan with milk or egg")
    if problems:
        sys.exit("\n".join(problems))


def write(foods):
    out = Path(__file__).resolve().parent.parent / "MacroMenu" / "GenericFoods.json"
    out.write_text(json.dumps(foods, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")
    print(f"Wrote {len(foods)} foods to {out}")


def apply_diet():
    """Sets each food's diet in the current GenericFoods.json, leaving its figures as they are."""
    out = Path(__file__).resolve().parent.parent / "MacroMenu" / "GenericFoods.json"
    foods = json.loads(out.read_text(encoding="utf-8"))
    check_diet([f["name"] for f in foods])
    for food in foods:
        food["diet"] = diet(food["name"])
    write(foods)


def number(value):
    return float(value) if value not in ("", None) else None


def entry(fdc, name, category, per100, grams, serve):
    """One food in the app's format, scaled from USDA's per-100 g figures to `grams`."""
    scale = grams / 100

    def scaled(key):
        value = per100.get(key)
        return None if value is None else round(value * scale, 1)

    cal = round(per100[ENERGY_KCAL] * scale, 1)
    kj = round(per100[ENERGY_KJ] * scale, 1) if ENERGY_KJ in per100 else round(cal * 4.184, 1)
    food = {
        "id": f"usda-{fdc}", "chain": "generic", "name": name, "cat": category,
        "kj": kj, "cal": cal, "p": scaled(PROTEIN), "c": scaled(CARBS), "f": scaled(FAT), "serve": serve,
    }
    extras = {key: scaled(nid) for key, nid in EXTRAS.items() if scaled(nid) is not None}
    if extras:
        food["nut"] = extras
    food["diet"] = diet(name)
    return food


def survey(folder):
    """The SURVEY_FOODS dishes from the FNDDS folder. Its portions are named in `portion_description` ("1 cup")."""
    wanted = {description for _, description, _, _, _ in SURVEY_FOODS}
    by_description = {}
    for food in rows(folder, "food.csv"):
        if food["description"] in wanted:
            by_description.setdefault(food["description"], []).append(food["fdc_id"])
    problems = [f"{name}: {len(by_description.get(d, []))} survey matches for {d!r}"
                for name, d, _, _, _ in SURVEY_FOODS if len(by_description.get(d, [])) != 1]
    if problems:
        sys.exit("\n".join(problems))
    ids = {by_description[d][0] for _, d, _, _, _ in SURVEY_FOODS}
    # This export keys nutrients by USDA's older numbers (208 for energy); nutrient.csv maps them to the ids used above.
    # Only whole numbers: "205.2" (carbs by summation) must not stand in for 205 (carbs by difference).
    by_number = {row["nutrient_nbr"].removesuffix(".0"): row["id"] for row in rows(folder, "nutrient.csv")
                 if row["nutrient_nbr"] and "." not in row["nutrient_nbr"].removesuffix(".0")}
    nutrients, portions = {}, {}
    for row in rows(folder, "food_nutrient.csv"):
        if row["fdc_id"] in ids:
            nutrient = by_number.get(row["nutrient_id"], row["nutrient_id"])
            nutrients.setdefault(row["fdc_id"], {})[nutrient] = float(row["amount"])
    for row in rows(folder, "food_portion.csv"):
        if row["fdc_id"] in ids:
            portions.setdefault(row["fdc_id"], []).append(row)
    foods = []
    for name, description, portion, category, label in SURVEY_FOODS:
        fdc = by_description[description][0]
        per100 = nutrients.get(fdc, {})
        match = [p for p in portions.get(fdc, []) if p["portion_description"].strip() == portion]
        if ENERGY_KCAL not in per100 or PROTEIN not in per100 or len(match) != 1:
            problems.append(f"{name}: missing energy, protein or the portion {portion!r}")
            continue
        grams = float(match[0]["gram_weight"])
        foods.append(entry(fdc, name, category, per100, grams, f"{label} ({grams:g} g)"))
    if problems:
        sys.exit("\n".join(problems))
    return foods


def main(folder, survey_folder):
    by_description = {}
    for food in rows(folder, "food.csv"):
        key = food["description"].removesuffix(SUFFIX)
        by_description.setdefault(key, []).append(food["fdc_id"])
    picked, problems = {}, []
    for name, description, _, _ in FOODS:
        ids = by_description.get(description, [])
        if len(ids) != 1:
            near = [d for d in by_description if d.lower().startswith(description.lower()[:20])][:5]
            problems.append(f"{name}: {len(ids)} matches for {description!r}; near: {near}")
        else:
            picked[ids[0]] = name
    if problems:
        sys.exit("\n".join(problems))

    nutrients = {}
    for row in rows(folder, "food_nutrient.csv"):
        if row["fdc_id"] in picked:
            nutrients.setdefault(row["fdc_id"], {})[row["nutrient_id"]] = float(row["amount"])
    portions = {}
    for row in rows(folder, "food_portion.csv"):
        if row["fdc_id"] in picked:
            portions.setdefault(row["fdc_id"], []).append(row)

    foods, problems = [], []
    for name, description, serving, category in FOODS:
        fdc = by_description[description][0]
        per100 = nutrients.get(fdc, {})
        kcal, protein = per100.get(ENERGY_KCAL), per100.get(PROTEIN)
        if kcal is None or protein is None:
            problems.append(f"{name}: no energy or protein")
            continue
        grams, serve = 100.0, "100 g"
        if serving:
            match = [p for p in portions.get(fdc, []) if p["modifier"].strip() == serving]
            if len(match) != 1:
                # Two portions can share a modifier ("6 inch sub", "12 inch sub"): the amount then tells them apart.
                match = [p for p in portions.get(fdc, []) if f"{float(p['amount']):g} {p['modifier'].strip()}" == serving]
            if len(match) != 1:
                options = [p["modifier"] for p in portions.get(fdc, [])]
                problems.append(f"{name}: portion {serving!r} not found once; options: {options}")
                continue
            portion = match[0]
            grams = float(portion["gram_weight"])
            amount = float(portion["amount"])
            count = f"{amount:g}" if amount != 0.5 else "½"
            label = re.sub(r"\s*\(.*?\)", "", serving).replace(" without refuse", "").strip().replace("tablespoon", "tbsp")
            serve = f"{count} {label} ({grams:g} g)"
        foods.append(entry(fdc, name, category, per100, grams, serve))
    if problems:
        sys.exit("\n".join(problems))
    foods += survey(survey_folder)
    names = [f["name"] for f in foods]
    assert len(set(names)) == len(names), "duplicate names"
    write(foods)


